/// The declarations as files: relative path → contents.
fn files_under(dir: &Path) -> BTreeMap<String, String> {
    let mut files = BTreeMap::new();
    let mut stack = vec![dir.to_path_buf()];
    while let Some(next) = stack.pop() {
        let Ok(entries) = std::fs::read_dir(&next) else {
            continue;
        };
        for entry in entries {
            let path = entry.expect("a directory entry").path();
            if path.is_dir() {
                stack.push(path);
            } else if path.extension().is_some_and(|ext| ext == "ts") {
                let relative = path.strip_prefix(dir).expect("under the directory");
                let text = std::fs::read_to_string(&path).expect("a readable declaration");
                files.insert(relative.to_string_lossy().replace('\\', "/"), text);
            }
        }
    }
    files
}

/// The declarations rendered now, in a fresh directory. The tests run in parallel in one
/// process, so each rendering gets a directory of its own.
fn rendered() -> BTreeMap<String, String> {
    static RENDERINGS: std::sync::atomic::AtomicUsize = std::sync::atomic::AtomicUsize::new(0);
    let rendering = RENDERINGS.fetch_add(1, std::sync::atomic::Ordering::SeqCst);
    let out = std::env::temp_dir().join(format!("ofm-bindings-{}-{rendering}", std::process::id()));
    let _ = std::fs::remove_dir_all(&out);
    export_roots(&config(&out));
    let mut files = files_under(&out);
    std::fs::remove_dir_all(&out).expect("the temporary directory is removed");
    add_indexes(&mut files);
    files
}

/// One `index.ts` per folder (`domain/`, `engine/`, `rules/`) re-exporting every declaration in
/// it, so a reader imports `bindings/core/engine` instead of one file per type.
fn add_indexes(files: &mut BTreeMap<String, String>) {
    let mut folders: BTreeMap<String, Vec<String>> = BTreeMap::new();
    for path in files.keys() {
        if let Some((folder, file)) = path.rsplit_once('/') {
            let name = file.trim_end_matches(".ts").to_string();
            folders.entry(folder.to_string()).or_default().push(name);
        }
    }
    for (folder, names) in folders {
        let mut index = String::from(
            "// This file was generated by ofm-bindings (src-tauri/crates/ofm-bindings). Do not edit \
             this file manually.\n",
        );
        for name in names {
            index.push_str(&format!("export type {{ {name} }} from \"./{name}\";\n"));
        }
        files.insert(format!("{folder}/index.ts"), index);
    }
}

/// Given the core types that cross to a client,
/// when their declarations are rendered,
/// then they are exactly the files committed under `src/bindings/core/`.
#[test]
fn the_declarations_match_the_committed_files() {
    let rendered = rendered();
    let dir = committed_dir();
    if std::env::var_os("UPDATE_BINDINGS").is_some() {
        let _ = std::fs::remove_dir_all(&dir);
        for (path, text) in &rendered {
            let target = dir.join(path);
            std::fs::create_dir_all(target.parent().expect("a parent")).expect("a directory");
            std::fs::write(target, text).expect("a declaration is written");
        }
    }
    assert!(
        files_under(&dir) == rendered,
        "src/bindings/core/ is out of date; run `UPDATE_BINDINGS=1 cargo test -p ofm-bindings`"
    );
}

/// Given the rendered declarations,
/// when they are searched for `bigint`,
/// then none is found: serde writes 64-bit integers as JSON numbers.
#[test]
fn no_declaration_uses_bigint() {
    let offenders: Vec<String> = rendered()
        .into_iter()
        .filter(|(_, text)| text.contains("bigint"))
        .map(|(path, _)| path)
        .collect();
    assert!(offenders.is_empty(), "declared as bigint: {offenders:?}");
}

/// The Rust sources of the crates whose types are declared.
fn core_sources() -> Vec<PathBuf> {
    let crates = Path::new(env!("CARGO_MANIFEST_DIR")).join("..");
    let mut sources = Vec::new();
    let mut stack: Vec<PathBuf> = ["domain", "engine", "ofm-rules"]
        .iter()
        .map(|name| crates.join(name).join("src"))
        .collect();
    while let Some(dir) = stack.pop() {
        for entry in std::fs::read_dir(&dir).expect("a readable source directory") {
            let path = entry.expect("a directory entry").path();
            if path.is_dir() {
                stack.push(path);
            } else if path.extension().is_some_and(|ext| ext == "rs") {
                sources.push(path);
            }
        }
    }
    sources
}

/// Fields of declared types that serde leaves out when empty but the declaration still requires,
/// as `file: field`. A declared item starts at its `derive(ts_rs::TS)` attribute and ends at the
/// first `}` in column 0.
fn skipped_fields_without_optional(source: &str, file: &str) -> Vec<String> {
    let mut found = Vec::new();
    let mut in_declared_item = false;
    let mut field_attributes: Vec<&str> = Vec::new();
    for line in source.lines() {
        if line.contains("derive(ts_rs::TS)") {
            in_declared_item = true;
            field_attributes.clear();
            continue;
        }
        if !in_declared_item {
            continue;
        }
        if line.starts_with('}') {
            in_declared_item = false;
            continue;
        }
        let trimmed = line.trim_start();
        if trimmed.starts_with("#[") || trimmed.starts_with("///") {
            field_attributes.push(trimmed);
            continue;
        }
        let skipped = field_attributes
            .iter()
            .any(|attribute| attribute.contains("skip_serializing_if"));
        let optional = field_attributes
            .iter()
            .any(|attribute| attribute.contains("ts(optional"));
        if skipped && !optional {
            found.push(format!("{file}: {}", trimmed.trim_end_matches(',')));
        }
        field_attributes.clear();
    }
    found
}

/// Given the declared core types,
/// when a field is left out of the JSON when it is empty (`skip_serializing_if`),
/// then its declaration marks it optional (`#[cfg_attr(feature = "ts", ts(optional))]`), so the
/// TypeScript says `field?: T` and not `field: T | null`.
#[test]
fn fields_serde_leaves_out_are_declared_optional() {
    let missing: Vec<String> = core_sources()
        .iter()
        .flat_map(|path| {
            let source = std::fs::read_to_string(path).expect("a readable source");
            skipped_fields_without_optional(&source, &path.display().to_string())
        })
        .collect();
    assert!(
        missing.is_empty(),
        "declare these optional:\n  {}",
        missing.join("\n  ")
    );
}

/// Given a declared struct whose field serde skips when empty,
/// when it has no `ts(optional)`, it is reported; when it has one, it is not.
#[test]
fn a_skipped_field_needs_optional() {
    let without = "#[cfg_attr(feature = \"ts\", derive(ts_rs::TS))]\npub struct A {\n    \
                   #[serde(skip_serializing_if = \"Option::is_none\")]\n    pub logo: Option<String>,\n}\n";
    let with = "#[cfg_attr(feature = \"ts\", derive(ts_rs::TS))]\npub struct A {\n    \
                #[serde(skip_serializing_if = \"Option::is_none\")]\n    \
                #[cfg_attr(feature = \"ts\", ts(optional))]\n    pub logo: Option<String>,\n}\n";
    assert_eq!(
        skipped_fields_without_optional(without, "a.rs"),
        vec!["a.rs: pub logo: Option<String>".to_string()]
    );
    assert!(skipped_fields_without_optional(with, "a.rs").is_empty());
}
