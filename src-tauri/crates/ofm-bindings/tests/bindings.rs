//! The TypeScript declarations of the core types that cross to a client, compared with the files
//! committed under `src/bindings/core/` (E3-6-tech-spec.md §3.2, E6-3).

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use ts_rs::{Config, TS};

/// Where the declarations are committed: `src/bindings/core/` at the repository root.
fn committed_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../../src/bindings/core")
}

/// `i64` and `u64` are written as `number`: serde writes them as JSON numbers, and ts-rs would
/// otherwise declare `bigint`.
fn config(out: &Path) -> Config {
    Config::new().with_large_int("number").with_out_dir(out)
}

