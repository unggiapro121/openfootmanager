"""Build `protected_people.txt` and `protected_clubs.txt` from Wikidata (CC0), E3-5q F6.

People: footballers and football managers with at least 20 Wikipedia articles; every player who
was ever a member of a national team of a nation in the online pack (senior, youth or women's,
`P54` to a subclass of national association football team); and every player who was ever a
member of a club of a Southeast Asian nation of the pack. Each with every Latin-script label and
alias. Clubs: every association football club of a nation in the pack, with every Latin-script
label and alias, under the pack nation it belongs to (the home nations told apart by location).

Usage: python3 protected.py   (writes ../protected_people.txt and ../protected_clubs.txt)
"""

import datetime
import os
import sys

from countries import HOME_NATIONS, NATIONS, SOUTHEAST_ASIA
from latin import clean
from wikidata import query

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.dirname(HERE)

NAMES = """
  { ?p rdfs:label ?name } UNION { ?p skos:altLabel ?name }
"""


def values(items):
    return " ".join(f"wd:{q}" for q in sorted(set(items)))


def famous_people():
    return query(f"""
SELECT DISTINCT ?p ?name WHERE {{
  VALUES ?occ {{ wd:Q937857 wd:Q628099 }}
  ?p wdt:P106 ?occ ; wikibase:sitelinks ?s . FILTER(?s >= 20)
  {NAMES}
}}""")


def national_team_players():
    countries = [q for q, _ in NATIONS.values()] + list(HOME_NATIONS.values())
    return query(f"""
SELECT DISTINCT ?p ?name WHERE {{
  VALUES ?country {{ {values(countries)} }}
  ?team wdt:P31/wdt:P279* wd:Q6979593 ; wdt:P17 ?country .
  ?p wdt:P54 ?team .
  {NAMES}
}}""")


def southeast_asian_club_players():
    countries = [NATIONS[code][0] for code in SOUTHEAST_ASIA]
    return query(f"""
SELECT DISTINCT ?p ?name WHERE {{
  VALUES ?country {{ {values(countries)} }}
  ?club wdt:P31/wdt:P279* wd:Q476028 ; wdt:P17 ?country .
  ?p wdt:P54 ?club .
  {NAMES}
}}""")


def clubs():
    countries = sorted({q for q, _ in NATIONS.values()})
    rows = query(f"""
SELECT DISTINCT ?club ?country ?name WHERE {{
  VALUES ?country {{ {values(countries)} }}
  ?club wdt:P31/wdt:P279* wd:Q476028 ; wdt:P17 ?country .
  {{ ?club rdfs:label ?name }} UNION {{ ?club skos:altLabel ?name }}
}}""")
    home = query(f"""
SELECT DISTINCT ?club ?home WHERE {{
  VALUES ?home {{ {values(HOME_NATIONS.values())} }}
  ?club wdt:P31/wdt:P279* wd:Q476028 ; wdt:P17 wd:Q145 .
  {{ ?club wdt:P131* ?home }} UNION {{ ?club wdt:P159/wdt:P131* ?home }}
}}""")
    home_of = {}
    by_item = {item: code for code, item in HOME_NATIONS.items()}
    for club, place in home:
        home_of.setdefault(club, set()).add(by_item[place])
    country_codes = {}
    for code, (item, _) in NATIONS.items():
        if code not in HOME_NATIONS:
            country_codes[item] = code
    out = set()
    for club, country, name in rows:
        name = clean(name)
        if not name:
            continue
        if country == "Q145":
            codes = home_of.get(club) or {"ENG"}
        else:
            codes = {country_codes[country]}
        for code in codes:
            out.add((code, name))
    return sorted(out)


def write(path, header, lines):
    with open(path, "w", encoding="utf-8") as out:
        for line in header:
            out.write(f"# {line}\n" if line else "#\n")
        for line in lines:
            out.write(line + "\n")


def main():
    today = datetime.date.today().isoformat()
    people = set()
    for label, rows in [
        ("famous", famous_people()),
        ("national teams", national_team_players()),
        ("Southeast Asian clubs", southeast_asian_club_players()),
    ]:
        names = {clean(name) for _, name in rows}
        names.discard(None)
        print(f"{label}: {len({p for p, _ in rows})} people, {len(names)} names", file=sys.stderr)
        people |= names
    write(
        os.path.join(DATA, "protected_people.txt"),
        [
            "People the generator never names a person after (E3-5q F6). Generated by",
            f"data/build/protected.py from Wikidata (CC0) through QLever, {today}: footballers and",
            "managers with 20 or more Wikipedia articles, every member of a national team of a pack",
            "nation, every member of a club of a Southeast Asian pack nation; every Latin-script label",
            "and alias. Hand-written additions: protected_people_vn.txt.",
            "Compared folded (lower case, no diacritics, hyphens, apostrophes or spaces) and in any",
            "rotation of its words, so \"Son Heung-min\" also blocks \"Heung-min Son\".",
        ],
        sorted(people),
    )
    club_lines = clubs()
    print(f"clubs: {len(club_lines)} names", file=sys.stderr)
    write(
        os.path.join(DATA, "protected_clubs.txt"),
        [
            "Clubs whose names the generator never gives a fictional club (E3-5q F6), as",
            f"`<nation code>|<name>`. Generated by data/build/protected.py from Wikidata (CC0) through",
            f"QLever, {today}: every association football club of a pack nation, every Latin-script",
            "label and alias. Hand-written additions: protected_clubs_vn.txt.",
            "A generated name is refused when it equals one folded, or when what is left of it after the",
            "common affixes (FC, United, City, Real, CLB…) equals what is left of one of the same nation.",
        ],
        [f"{code}|{name}" for code, name in club_lines],
    )


if __name__ == "__main__":
    main()
